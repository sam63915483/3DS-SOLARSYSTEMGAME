#define GLYPH_COUNT ((int)(sizeof(glyphs) / sizeof(glyphs[0])))

/* Square atlas: 8 cells per row, 8x8 pixel cells, one cell per ASCII code 32..95. */
#define ATLAS 64
#define CELL 8
#define CELLS_PER_ROW 8

static C3D_Tex tex;
static int ready;

/* Index of pixel (x, y) in the GPU's tiled (8x8 Morton) layout of an ATLAS x ATLAS texture. */
static int tiled_index(int x, int y) {
    int tile = (y / 8) * (ATLAS / 8) + (x / 8);
    int lx = x & 7, ly = y & 7;
    int within = (lx & 1) | ((ly & 1) << 1) | ((lx & 2) << 1) | ((ly & 2) << 2) | ((lx & 4) << 2) | ((ly & 4) << 3);
    return tile * 64 + within;
}

/* The GPU showed the naive layout rotated a quarter turn, so store each intended pixel
   (ix, iy) rotated the other way. */
static void put_pixel(u32 *px, int ix, int iy) {
    px[tiled_index(iy, ATLAS - 1 - ix)] = 0xFFFFFFFF;
}

static int glyph_code(char ch) {
    if (ch >= 'a' && ch <= 'z') ch -= 32;
    if (ch < 32 || ch > 95) return -1;
    return ch - 32;
}

void font_init(void) {
    if (!C3D_TexInit(&tex, ATLAS, ATLAS, GPU_RGBA8)) return;
    u32 *px = (u32 *)tex.data;
    memset(px, 0, tex.size);
    for (int g = 0; g < GLYPH_COUNT; g++) {
        int code = glyph_code(glyphs[g].ch);
        if (code < 0) continue;
        int cx = (code % CELLS_PER_ROW) * CELL, cy = (code / CELLS_PER_ROW) * CELL;
        for (int r = 0; r < 7; r++)
            for (int c = 0; c < 5; c++)
                if (glyphs[g].rows[r][c] == '#') put_pixel(px, cx + c, cy + r);
    }
    C3D_TexSetFilter(&tex, GPU_NEAREST, GPU_NEAREST);
    C3D_TexSetWrap(&tex, GPU_CLAMP_TO_EDGE, GPU_CLAMP_TO_EDGE);
    GSPGPU_FlushDataCache(tex.data, tex.size);
    ready = 1;
}

void font_fini(void) { if (ready) C3D_TexDelete(&tex); ready = 0; }

void font_draw(const char *s, float x, float y, float scale, u32 color) {
    if (!ready) return;
    C2D_ImageTint tint;
    C2D_PlainImageTint(&tint, color, 1.0f);
    for (; *s; s++) {
        int code = glyph_code(*s);
        if (code > 0) {
            int cx = (code % CELLS_PER_ROW) * CELL, cy = (code / CELLS_PER_ROW) * CELL;
            Tex3DS_SubTexture sub;
            sub.width = 6; sub.height = 8;
            sub.left = cx / (float)ATLAS;
            sub.right = (cx + 6) / (float)ATLAS;
            sub.top = cy / (float)ATLAS;
            sub.bottom = (cy + 8) / (float)ATLAS;
            C2D_Image img = { &tex, &sub };
            C2D_DrawImageAt(img, x, y, 0, &tint, scale, scale);
        }
        x += 6 * scale;
    }
}

float font_width(const char *s, float scale) { return (float)strlen(s) * 6 * scale; }

void font_debug_atlas(float x, float y, float scale) {
    if (!ready) return;
    Tex3DS_SubTexture sub = { ATLAS, ATLAS, 0.0f, 0.0f, 1.0f, 1.0f };
    C2D_Image img = { &tex, &sub };
    C2D_DrawImageAt(img, x, y, 0, NULL, scale, scale);
}
